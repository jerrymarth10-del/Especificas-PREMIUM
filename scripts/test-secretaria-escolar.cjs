const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {buildSecretariaEscolar,insertSecretariaEscolar}=require('../lib/secretaria-escolar');
const {lessons,exams}=require('../lib/secretaria-escolar-conteudo.json');
const art=require('../lib/secretaria-escolar-art.json');
assert.equal(lessons.length,34,'São esperadas 34 aulas verificadas');
assert.ok(new Set(lessons.map(x=>x.video)).size===34,'As aulas não podem repetir vídeos');
assert.ok(lessons.every(x=>/^[A-Za-z0-9_-]{11}$/.test(x.video)));
assert.ok(new Set(lessons.map(x=>x.group)).size>=6);
assert.equal(exams.length,2);
assert.ok(exams.every(x=>x.board==='IBGP'&&x.url.startsWith('https://www.pciconcursos.com.br/provas/download/')));
assert.ok(art.startsWith('data:image/svg+xml;base64,'));
const image=Buffer.from(art.split(',')[1],'base64').toString('utf8');
assert.match(image,/viewBox="0 0 640 960"/);
assert.match(image,/SECRETARIA/);
const locked=buildSecretariaEscolar(false);
const unlocked=buildSecretariaEscolar(true);
assert.match(locked.card,/data-jr-card="secretariaescolar"/);
assert.match(locked.card,/class="card jr-se-card jr-approved-art-card"/);
assert.match(locked.card,/class="card-btn"/);
assert.equal(locked.area,'','Conteúdo não pode ser entregue sem autorização');
assert.match(unlocked.area,/id="area-secretariaescolar"/);
assert.equal((unlocked.area.match(/data-video=/g)||[]).length,34);
assert.match(unlocked.area,/Provas anteriores IBGP/);
assert.match(unlocked.script,/jrAbrirSecretariaEscolar/);
const {buildCuidadorSocial}=require('../lib/cuidador-social');
const sample='<html><head></head><body><main>'+buildCuidadorSocial().card+'</main><footer class="footer"></footer></body></html>';
const unauthorized=insertSecretariaEscolar(sample,false);
assert.equal((unauthorized.match(/data-jr-card="secretariaescolar"/g)||[]).length,1);
assert.ok(!unauthorized.includes('id="area-secretariaescolar"'));
const authorized=insertSecretariaEscolar(sample,true);
assert.equal((authorized.match(/data-jr-card="secretariaescolar"/g)||[]).length,1);
assert.ok(authorized.includes('id="area-secretariaescolar"'));
assert.equal(insertSecretariaEscolar(authorized,true),authorized,'Idempotência da injeção');
const inject=fs.readFileSync(path.join(__dirname,'..','api/inject.js'),'utf8');
assert.match(inject,/insertSecretariaEscolar\(html,/);
assert.match(inject,/hasManualSecretariaEscolar\(req\)/);
assert.match(inject,/if\(area==='secretariaescolar'&&!document.getElementById/);
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'..','vercel.json'),'utf8'));
assert.ok(cfg.routes.some(x=>x.src.includes('secretaria-escolar')));
const helper=fs.readFileSync(path.join(__dirname,'..','lib/secretaria-escolar-access.js'),'utf8');
assert.match(helper,/JR_SECRETARIA_ESCOLAR_PASSWORD/);
assert.doesNotMatch(helper,/SECRETARIA2026/,'Não publicar senha manual em repositório público');
const checkoutFiles=['api/checkout.js','api/payment.js'];
for(const f of checkoutFiles)assert.ok(!fs.existsSync(path.join(__dirname,'..',f)),'Projeto 2 não deve copiar checkout');
console.log('OK: Secretaria Escolar (conteúdo + arte + card + proteção manual/compra)');
